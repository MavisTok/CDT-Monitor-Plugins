import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { releaseInfo } from './release-info.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const release = releaseInfo(pkg);
// Keep the parameter schema and runtime on the same release, even when main advances.
const remoteRoot = release.scriptRoot + 'surge/';
const core = fs.readFileSync(path.join(root, 'src/core.js'), 'utf8');
const platform = fs.readFileSync(path.join(root, 'src/platform.js'), 'utf8');
for (const dir of ['surge', 'loon', 'egern', 'stash']) fs.mkdirSync(path.join(root, dir), { recursive: true });
const parameters = JSON.parse(fs.readFileSync(path.join(root, 'src/module-parameters.json'), 'utf8'));
const parameterDefaults = Object.fromEntries(parameters.map(p => [p.key, p.default]));
const moduleConfig = 'var MODULE_PARAMETER_DEFAULTS = ' + JSON.stringify(parameterDefaults) + ';\n' + fs.readFileSync(path.join(root, 'src/module-config.js'), 'utf8');
const banner = '// Generated by tools/build.mjs. Surge runtime needs no Node or external dependencies.\n';
const config = fs.readFileSync(path.join(root, 'config.example.json'), 'utf8').trim();
for (const setupPath of ['cdt-setup.js', ...['surge', 'loon', 'egern', 'stash'].map(dir => dir + '/cdt-setup.js')].map(p => path.join(root, p))) {
if (fs.existsSync(setupPath)) {
  const old = fs.readFileSync(setupPath, 'utf8');
  const oldConfig = old.split('var LOCAL_CONFIG = ')[1]?.split(';\n\n' + banner)[0];
  if (oldConfig && JSON.stringify(JSON.parse(oldConfig)) !== JSON.stringify(JSON.parse(config))) {
    throw new Error('cdt-setup.js contains edited local configuration. Move it to cdt-setup.private.js before rebuilding; it will not be overwritten.');
  }
}
}
for (const dir of ['surge', 'loon', 'egern', 'stash']) {
  const monitor = banner + core + '\n' + platform + '\n' + moduleConfig + '\n' + fs.readFileSync(path.join(root, 'src/runtime.js'), 'utf8');
  const setup = '// Edit only LOCAL_CONFIG below on your own device. Never publish your populated copy.\nvar LOCAL_CONFIG = ' + config + ';\n\n' + banner + core + '\n' + platform + '\n' + fs.readFileSync(path.join(root, 'src/setup.js'), 'utf8');
  const wrap = code => dir === 'egern' ? fs.readFileSync(path.join(root, 'src/egern-wrapper.js'), 'utf8').replace('    /* CDT_SHARED_RUNTIME */', code) : code;
  fs.writeFileSync(path.join(root, dir, 'cdt-monitor.js'), wrap(monitor));
  fs.writeFileSync(path.join(root, dir, 'cdt-setup.js'), wrap(setup));
}

function makeModule(scriptRoot, ios) {
  const monitor = scriptRoot + 'cdt-monitor.js', setup = scriptRoot + 'cdt-setup.js';
  const platform = ios ? '' : '#!system=mac\n';
  const wake = ios ? ',wake-system=true' : '';
  const metadata = parameters.map(p => {
    if (typeof p.default !== 'string' || p.default === '') throw new Error('Every module parameter needs a nonempty default: ' + p.key);
    return p.key + ':' + p.default;
  }).join(',');
  const argument = op => 'cdt-module-v1|op=' + op + '|' + parameters.map(p => p.key + '={{{' + p.key + '}}}').join('|');
  return `#!name=CDT Monitor 本地版\n#!desc=v${pkg.version} · 直接查询阿里云 CDT/ECS/BSS；在模块参数表中填写账号与监控设置，保存后下次执行生效。\n${platform}#!arguments=${metadata}\n#!arguments-desc=config_source=module 使用本表（单账号实例），local 使用原多账号 JSON。请将 access_key_id、access_key_secret 的“未设置”替换为真实密钥。可选项保留“未设置”，不要清空；instance_id 为“未设置”时仅监控流量；daily_report_time 填“关闭”可停用日报。max_traffic_gib 请填实际额度。开关填写 true/false，时间填写 HH:mm；threshold_action=notify/stop，site_type=china/international。默认关闭控制。参数值不使用竖线、英文双引号或换行。\n\n[Script]\nCDT-Setup = type=generic,script-path="${setup}",timeout=10,debug=true\nCDT-Panel = type=generic,script-path="${monitor}",argument="${argument('panel')}",timeout=120\nCDT-Monitor = type=cron,cronexp="*/10 * * * *",script-path="${monitor}",argument="${argument('monitor')}",timeout=120${wake}\nCDT-Refresh = type=generic,script-path="${monitor}",argument="${argument('refresh')}",timeout=120\nCDT-History = type=generic,script-path="${monitor}",argument="${argument('history')}",timeout=10\nCDT-Notify-Test = type=generic,script-path="${monitor}",argument="${argument('test-notify')}",timeout=120\nCDT-Control = type=generic,script-path="${monitor}",argument="${argument('refresh')}",timeout=120\n\n[Panel]\nCDT Monitor = script-name=CDT-Panel,title="CDT Monitor",content="请在模块参数中填写账号",update-interval=600\n`;
}
for (const [name, scriptRoot, ios] of [
  ['CDT-Monitor.sgmodule', remoteRoot, true],
  ['CDT-Monitor-Mac.sgmodule', remoteRoot, false],
  ['CDT-Monitor-Local.sgmodule', '', true],
  ['CDT-Monitor-Local-Mac.sgmodule', '', false]
]) {
  // Keep the metadata at byte zero, before comments, whitespace or sections.
  fs.writeFileSync(path.join(root, 'surge', name), makeModule(scriptRoot, ios));
}
const bindings = '{' + parameters.map(p => '${' + p.key + '}').join(', ') + '}';
const loonRoot = release.scriptRoot + 'loon/';
const labels = {
  config_source: '配置来源', account_id: '账号记录ID', account_name: '显示名称',
  access_key_id: '必填·AccessKey ID', access_key_secret: '必填·AccessKey Secret',
  region_id: '实例地域', instance_id: '实例ID（仅查流量可不填）', site_type: '阿里云站点',
  max_traffic_gib: '流量额度GiB', threshold_percent: '告警阈值百分比', allow_control: '实例控制总开关',
  threshold_action: '达到阈值后的操作', shutdown_mode: '停机模式', keep_alive: '实例保活',
  schedule_enabled: '定时启停开关', start_time: '每天启动时间', stop_time: '每天停止时间',
  billing: '查询余额与账单', daily_report_time: '日报时间', timezone_offset_minutes: '时区偏移分钟',
  request_timeout_seconds: '请求超时秒数', system_notification: '系统通知开关',
  telegram_enabled: 'Telegram通知开关', telegram_base_url: 'Telegram接口地址',
  telegram_bot_token: 'Telegram机器人Token', telegram_chat_id: 'Telegram接收者ID',
  webhook_enabled: 'Webhook通知开关', webhook_url: 'Webhook地址', webhook_authorization: 'Webhook认证'
};
const descriptions = {
  config_source: '普通单账号保持module：填好两项密钥并保存后运行CDT-Refresh；local用于已导入的高级多账号JSON',
  access_key_id: '必填：与AccessKey Secret配对。只填ID不能查询；保存后运行CDT-Refresh，不要运行CDT-Setup',
  access_key_secret: '必填：填写该AccessKey ID对应的Secret；参数表模式无需导入JSON'
};
const declarations = parameters.map(p => `${p.key} = input,${JSON.stringify(p.default)},type=string,tag=${JSON.stringify(labels[p.key] || p.key)},desc=${JSON.stringify(descriptions[p.key] || p.description)}`).join('\n');
const taskDescriptions = {
  'CDT-Monitor': '自动监控：每10分钟查询，执行已开启的自动策略、日报及通知重试',
  'CDT-Refresh': '日常使用：手动查询流量、实例和可选账单，不执行自动启停',
  'CDT-History': '查看历史：将小时、日快照及操作记录输出到脚本日志',
  'CDT-Notify-Test': '测试通知：向已启用的系统、Telegram和Webhook通道发送测试消息',
  'CDT-Start': '手动开机：需开启控制总开关并填写控制账号及完整实例ID',
  'CDT-Stop': '手动关机：需开启控制总开关并填写控制账号及完整实例ID'
};
const usage = '首次使用：保持config_source=module，填写AccessKey ID和Secret两项并保存，然后运行CDT-Refresh。普通模式不要运行CDT-Setup。\\n脚本用途：CDT-Refresh＝查询流量与状态；CDT-History＝历史日志；CDT-Notify-Test＝测试通知；CDT-Start＝手动开机；CDT-Stop＝手动关机；CDT-Monitor＝每10分钟自动监控。\\nCDT-Setup＝仅高级JSON导入：先填config_json再运行，未填JSON只显示使用引导，不保存配置。';
const tasks = [['CDT-Monitor', 'cron "*/10 * * * *"'], ['CDT-Refresh', 'generic'], ['CDT-History', 'generic'], ['CDT-Notify-Test', 'generic'], ['CDT-Start', 'generic'], ['CDT-Stop', 'generic']];
const scripts = tasks.map(([tag, trigger]) => {
  const args = /CDT-(Start|Stop)$/.test(tag) ? bindings.slice(0, -1) + ', ${control_account}, ${control_confirm}}' : bindings;
  return `# ${tag}：${taskDescriptions[tag]}\n${trigger} then script("${loonRoot}cdt-monitor.js", ${args}) with tag="${tag}", timeout=120`;
});
fs.writeFileSync(path.join(root, 'loon/CDT-Monitor.plugin'), `#!name=CDT Monitor\n#!desc=v${pkg.version} · 阿里云 CDT/ECS/BSS 本地监控；默认只读。\\n${usage}\n#!loon_version=3.5.1(983)\n\n[Argument]\n${declarations}\ncontrol_account = input,"ecs-1",tag=手动控制账号ID,desc=仅CDT-Start和CDT-Stop使用；必须匹配账号记录ID\ncontrol_confirm = input,"未设置",tag=手动控制完整实例ID,desc=仅手动启停使用；必须与目标实例ID完全一致\nconfig_json = input,"",tag=高级JSON导入（普通用户留空）,desc=仅高级多账号使用：先填写完整JSON再运行CDT-Setup；普通用户填两项密钥后运行CDT-Refresh即可\n\n[Script]\n${scripts.join('\n')}\n# CDT-Setup：仅导入高级config_json；普通参数表用户无需运行，查看流量请运行CDT-Refresh\ngeneric then script("${loonRoot}cdt-setup.js", {\${config_json}}) with tag="CDT-Setup", timeout=10\n`);
// JSON is a YAML subset: avoid custom quoting/serialization for credentials and metadata.
const saveYaml = (file, value) => fs.writeFileSync(path.join(root, file), JSON.stringify(value, null, 2) + '\n');
const extras = [
  { key: 'control_account', default: 'ecs-1', description: '仅手动启停：目标账号记录ID', title: '手动控制账号ID' },
  { key: 'control_confirm', default: '未设置', description: '仅手动启停：必须精确匹配完整实例ID', title: '手动控制实例确认' },
  { key: 'config_json', default: '', description: '仅高级多账号导入；普通用户留空，不运行Setup', title: '高级JSON导入' }
];
const all = [...parameters, ...extras];
const help = `v${pkg.version} · 阿里云CDT监控。填好AccessKey ID与Secret并保存后查询；普通用户不运行Setup。刷新与面板只查询；Monitor每10分钟执行已启用的自动策略。History查看日志；Notify-Test测试通知；Start/Stop手动启停；Setup只导入完整高级JSON。`;
const defaults = Object.fromEntries(all.map(p => [p.key, p.default]));
const egernTasks = [...tasks.map(([name]) => name), 'CDT-Setup'];
saveYaml('egern/CDT-Monitor.yaml', {
  name: 'CDT Monitor', description: help,
  homepage: pkg.repository.url.replace(/\.git$/, ''),
  manual: release.guide.replace('README.md', 'egern/README.md'),
  env_schema: Object.fromEntries(all.map(p => [p.key, { name: p.title || labels[p.key] || p.key, description: descriptions[p.key] || p.description, default_value: p.default }])),
  scriptings: egernTasks.map(name => ({ [name === 'CDT-Monitor' ? 'schedule' : 'generic']: {
    name, ...(name === 'CDT-Monitor' ? { cron: '*/10 * * * *' } : {}),
    script_url: release.scriptRoot + 'egern/' + (name === 'CDT-Setup' ? 'cdt-setup.js' : 'cdt-monitor.js'),
    timeout: name === 'CDT-Setup' ? 10 : 120, update_interval: 86400,
    env: Object.fromEntries(Object.entries(defaults).filter(([key]) => name === 'CDT-Setup' ? key === 'config_json' : key !== 'config_json' && (/CDT-(Start|Stop)$/.test(name) || !key.startsWith('control_'))))
  } })),
  widgets: [{ name: 'CDT-Refresh' }]
});
// Stash interpolates |json values into a string argument, then the runtime parses it.
const stashArgument = keys => '{' + keys.map(key => JSON.stringify(key) + ':${args.' + key + '|json}').join(',') + '}';
const monitorKeys = parameters.map(p => p.key);
saveYaml('stash/CDT-Monitor.stoverride', {
  name: 'CDT Monitor', desc: help + ' 参数表要求iOS/tvOS 3.7+或macOS 4.4+（Beta）。手动启停只能在编辑器执行，切勿添加到Tile或定时任务。',
  'arguments-version': 1,
  arguments: Object.fromEntries(all.map(p => [p.key, { type: 'input', title: p.title || labels[p.key] || p.key, description: descriptions[p.key] || p.description, default: p.default }])),
  'script-providers': Object.fromEntries(egernTasks.map(name => [name, { url: release.scriptRoot + 'stash/' + (name === 'CDT-Setup' ? 'cdt-setup.js' : 'cdt-monitor.js'), interval: 86400 }])),
  cron: { script: [{ name: 'CDT-Monitor', cron: '*/10 * * * *', argument: stashArgument(monitorKeys), timeout: 120 }] },
  tiles: [{ name: 'CDT-Refresh', interval: 600, title: 'CDT Monitor · 点击查询', content: '在覆写参数中填写ID和Secret；普通用户无需Setup', argument: stashArgument(monitorKeys) }]
});
