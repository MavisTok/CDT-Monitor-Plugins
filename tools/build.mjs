import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { releaseInfo } from './release-info.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const release = releaseInfo(pkg);
// Keep the parameter schema and runtime on the same release, even when main advances.
const remoteRoot = release.scriptRoot + 'surge/';
const core = fs.readFileSync(path.join(root, 'src/core.js'), 'utf8');
const platform = fs.readFileSync(path.join(root, 'src/platform.js'), 'utf8');
for (const dir of ['surge', 'loon']) fs.mkdirSync(path.join(root, dir), { recursive: true });
const parameters = JSON.parse(fs.readFileSync(path.join(root, 'src/module-parameters.json'), 'utf8'));
const parameterDefaults = Object.fromEntries(parameters.map(p => [p.key, p.default]));
const moduleConfig = 'var MODULE_PARAMETER_DEFAULTS = ' + JSON.stringify(parameterDefaults) + ';\n' + fs.readFileSync(path.join(root, 'src/module-config.js'), 'utf8');
const banner = '// Generated by tools/build.mjs. Surge runtime needs no Node or external dependencies.\n';
const config = fs.readFileSync(path.join(root, 'config.example.json'), 'utf8').trim();
for (const setupPath of ['cdt-setup.js', 'surge/cdt-setup.js', 'loon/cdt-setup.js'].map(p => path.join(root, p))) {
if (fs.existsSync(setupPath)) {
  const old = fs.readFileSync(setupPath, 'utf8');
  const oldConfig = old.split('var LOCAL_CONFIG = ')[1]?.split(';\n\n' + banner)[0];
  if (oldConfig && JSON.stringify(JSON.parse(oldConfig)) !== JSON.stringify(JSON.parse(config))) {
    throw new Error('cdt-setup.js contains edited local configuration. Move it to cdt-setup.private.js before rebuilding; it will not be overwritten.');
  }
}
}
for (const dir of ['surge', 'loon']) {
  fs.writeFileSync(path.join(root, dir, 'cdt-monitor.js'), banner + core + '\n' + platform + '\n' + moduleConfig + '\n' + fs.readFileSync(path.join(root, 'src/runtime.js'), 'utf8'));
  fs.writeFileSync(path.join(root, dir, 'cdt-setup.js'), '// Edit only LOCAL_CONFIG below on your own device. Never publish your populated copy.\nvar LOCAL_CONFIG = ' + config + ';\n\n' + banner + core + '\n' + platform + '\n' + fs.readFileSync(path.join(root, 'src/setup.js'), 'utf8'));
}

function makeModule(scriptRoot, ios) {
  const monitor = scriptRoot + 'cdt-monitor.js', setup = scriptRoot + 'cdt-setup.js';
  const platform = ios ? '' : '#!system=mac\n';
  const wake = ios ? ',wake-system=true' : '';
  const metadata = parameters.map(p => {
    if (typeof p.default !== 'string' || p.default === '') throw new Error('Every module parameter needs a nonempty default: ' + p.key);
    return p.key + ':' + p.default;
  }).join(',');
  const argument = op => 'cdt-module-v1|op=' + op + '|' + parameters.map(p => p.key + '={{{' + p.key + '}}}').join('|');
  return `#!name=CDT Monitor 本地版\n#!desc=v${pkg.version} · 直接查询阿里云 CDT/ECS/BSS；在模块参数表中填写账号与监控设置，保存后下次执行生效。\n${platform}#!arguments=${metadata}\n#!arguments-desc=config_source=module 使用本表（单账号实例），local 使用原多账号 JSON。请将 access_key_id、access_key_secret 的“未设置”替换为真实密钥。可选项保留“未设置”，不要清空；instance_id 为“未设置”时仅监控流量；daily_report_time 填“关闭”可停用日报。max_traffic_gib 请填实际额度。开关填写 true/false，时间填写 HH:mm；threshold_action=notify/stop，site_type=china/international。默认关闭控制。参数值不使用竖线、英文双引号或换行。\n\n[Script]\nCDT-Setup = type=generic,script-path="${setup}",timeout=10,debug=true\nCDT-Panel = type=generic,script-path="${monitor}",argument="${argument('panel')}",timeout=120\nCDT-Monitor = type=cron,cronexp="*/10 * * * *",script-path="${monitor}",argument="${argument('monitor')}",timeout=120${wake}\nCDT-Refresh = type=generic,script-path="${monitor}",argument="${argument('refresh')}",timeout=120\nCDT-History = type=generic,script-path="${monitor}",argument="${argument('history')}",timeout=10\nCDT-Notify-Test = type=generic,script-path="${monitor}",argument="${argument('test-notify')}",timeout=120\nCDT-Control = type=generic,script-path="${monitor}",argument="${argument('refresh')}",timeout=120\n\n[Panel]\nCDT Monitor = script-name=CDT-Panel,title="CDT Monitor",content="请在模块参数中填写账号",update-interval=600\n`;
}
for (const [name, scriptRoot, ios] of [
  ['CDT-Monitor.sgmodule', remoteRoot, true],
  ['CDT-Monitor-Mac.sgmodule', remoteRoot, false],
  ['CDT-Monitor-Local.sgmodule', '', true],
  ['CDT-Monitor-Local-Mac.sgmodule', '', false]
]) {
  // Keep the metadata at byte zero, before comments, whitespace or sections.
  fs.writeFileSync(path.join(root, 'surge', name), makeModule(scriptRoot, ios));
}
const bindings = '{' + parameters.map(p => '${' + p.key + '}').join(', ') + '}';
const loonRoot = release.scriptRoot + 'loon/';
const declarations = parameters.map(p => `${p.key} = input,${JSON.stringify(p.default)},type=string,tag=${p.key}`).join('\n');
const tasks = [['CDT-Monitor', 'cron "*/10 * * * *"'], ['CDT-Refresh', 'generic'], ['CDT-History', 'generic'], ['CDT-Notify-Test', 'generic'], ['CDT-Start', 'generic'], ['CDT-Stop', 'generic']];
const scripts = tasks.map(([tag, trigger]) => {
  const args = /CDT-(Start|Stop)$/.test(tag) ? bindings.slice(0, -1) + ', ${control_account}, ${control_confirm}}' : bindings;
  return `${trigger} then script("${loonRoot}cdt-monitor.js", ${args}) with tag="${tag}", timeout=120`;
});
fs.writeFileSync(path.join(root, 'loon/CDT-Monitor.plugin'), `#!name=CDT Monitor\n#!desc=v${pkg.version} · 阿里云 CDT/ECS/BSS 本地监控；默认只读。\n#!loon_version=3.5.1(983)\n\n[Argument]\n${declarations}\ncontrol_account = input,"ecs-1",tag=手动控制账号ID\ncontrol_confirm = input,"未设置",tag=手动控制完整实例ID\nconfig_json = input,"",tag=高级多账号JSON,desc=仅手动运行CDT-Setup时导入\n\n[Script]\n${scripts.join('\n')}\ngeneric then script("${loonRoot}cdt-setup.js", {\${config_json}}) with tag="CDT-Setup", timeout=10\n`);
fs.writeFileSync(path.join(root, 'INSTALL-URLS.txt'), `CDT Monitor 持续更新安装地址\n\nSurge iOS\n${release.install.ios}\n\nSurge Mac\n${release.install.mac}\n\nLoon\n${release.install.loon}\n\n旧根目录来源需迁移到平台子目录。安装入口跟随 main；配套版本标签发布后远程脚本才可下载。\n`);
console.log(`Built v${pkg.version}: surge/ modules, loon/ plugin, shared scripts and installation URLs.`);
